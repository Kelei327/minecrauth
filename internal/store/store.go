// Package store defines the persistence interfaces and models.
package store

import (
	"context"
	"errors"
	"time"
)

// Sentinel errors for persistence operations.
var (
	ErrNotFound = errors.New("resource not found")
	ErrConflict = errors.New("resource conflict")
)

// User represents a physical account owner in the system.
type User struct {
	ID                string    `json:"id"`
	Email             string    `json:"email"`
	PasswordHash      string    `json:"-"`
	GamePasswordHash  string    `json:"-"`
	GamePasswordSet   bool      `json:"game_password_set"`
	IsAdmin           bool      `json:"is_admin"`
	Blocked           bool      `json:"blocked"`
	EmailVerified     bool      `json:"email_verified"`
	PreferredLanguage string    `json:"preferred_language"`
	TOTPSecret        string    `json:"-"`            // base32 TOTP secret; empty when 2FA is off
	TOTPEnabled       bool      `json:"totp_enabled"` // true once confirmed; exposed to the UI
	CreatedAt         time.Time `json:"created_at"`
	UpdatedAt         time.Time `json:"updated_at"`
}

const (
	AuthTokenPasswordReset = "password_reset"
	AuthTokenEmailVerify   = "email_verify"
	AuthTokenTOTPPending   = "totp_pending"
)

// AuthToken is a single-use, hashed token for out-of-band flows (password reset,
// email verification). The plaintext token is delivered to the user via a link;
// only its SHA-256 hash is persisted so a database leak does not expose usable tokens.
type AuthToken struct {
	TokenHash string     `json:"token_hash"` // hex-encoded SHA-256 of the plaintext token (primary key)
	UserID    string     `json:"user_id"`
	Purpose   string     `json:"purpose"` // "password_reset" | "email_verify"
	CreatedAt time.Time  `json:"created_at"`
	ExpiresAt time.Time  `json:"expires_at"`
	UsedAt    *time.Time `json:"used_at"` // nil until consumed
}

// Session is a browser login session backing the Web UI cookie.
type Session struct {
	Token          string    `json:"-"`
	UserID         string    `json:"-"`
	CSRFToken      string    `json:"-"`
	ImpersonatedBy *string   `json:"-"` // real admin user id when this is an impersonation session; nil otherwise
	CreatedAt      time.Time `json:"-"`
	ExpiresAt      time.Time `json:"-"`
}

// Player represents a Minecraft in-game profile associated with a User.
type Player struct {
	ID            string     `json:"id"`
	UserID        string     `json:"user_id"`
	Name          string     `json:"name"`
	UUID          string     `json:"uuid"` // Canonical UUID representation with dashes
	CreatedAt     time.Time  `json:"created_at"`
	NameChangedAt *time.Time `json:"name_changed_at"`
	// Texture fields added in migration 5.
	SkinHash  *string `json:"skin_hash"`
	SkinModel *string `json:"skin_model"`
	CapeHash  *string `json:"cape_hash"`
}

// YggdrasilToken represents an authentication session token used by players to join servers.
type YggdrasilToken struct {
	AccessToken string     `json:"access_token"`
	ClientToken string     `json:"client_token"`
	UserID      string     `json:"user_id"`
	PlayerID    *string    `json:"player_id"` // Selected profile, can be null
	CreatedAt   time.Time  `json:"created_at"`
	ExpiresAt   *time.Time `json:"expires_at"` // Nullable; null means never expires
}

// Invite represents a registration invite code generated by an admin.
type Invite struct {
	Code      string     `json:"code"`
	CreatedBy string     `json:"created_by"` // UserID of admin
	UsedBy    *string    `json:"used_by"`    // Nullable UserID
	CreatedAt time.Time  `json:"created_at"`
	ExpiresAt *time.Time `json:"expires_at"` // Nullable
}

// Store defines the data access and lifecycle operations.
type Store interface {
	// Lifecycle
	Migrate(ctx context.Context) error
	Ping(ctx context.Context) error
	Close() error

	// User CRUD
	CreateUser(ctx context.Context, u *User) error
	GetUserByID(ctx context.Context, id string) (*User, error)
	GetUserByEmail(ctx context.Context, email string) (*User, error)
	UpdateUser(ctx context.Context, u *User) error
	DeleteUser(ctx context.Context, id string) error
	ListUsers(ctx context.Context) ([]*User, error)

	// Player ops
	CreatePlayer(ctx context.Context, p *Player) error
	GetPlayerByID(ctx context.Context, id string) (*Player, error)
	GetPlayerByName(ctx context.Context, name string) (*Player, error)
	GetPlayerByUUID(ctx context.Context, uuid string) (*Player, error)
	ListPlayersByUser(ctx context.Context, userID string) ([]*Player, error)
	// ListAllPlayers returns every player in the store. Used for offline-UUID reverse lookup.
	ListAllPlayers(ctx context.Context) ([]*Player, error)
	UpdatePlayer(ctx context.Context, p *Player) error
	DeletePlayer(ctx context.Context, id string) error
	CountPlayersByUser(ctx context.Context, userID string) (int, error)

	// Token ops
	CreateToken(ctx context.Context, t *YggdrasilToken) error
	GetToken(ctx context.Context, accessToken string) (*YggdrasilToken, error)
	DeleteToken(ctx context.Context, accessToken string) error
	DeleteTokensByUser(ctx context.Context, userID string) error
	DeleteExpiredTokens(ctx context.Context) error

	// Invite ops
	CreateInvite(ctx context.Context, i *Invite) error
	GetInvite(ctx context.Context, code string) (*Invite, error)
	MarkInviteUsed(ctx context.Context, code string, userID string) error
	DeleteInvite(ctx context.Context, code string) error
	ListInvites(ctx context.Context) ([]*Invite, error)

	// Session ops (browser UI sessions, distinct from Yggdrasil tokens)
	CreateSession(ctx context.Context, s *Session) error
	GetSession(ctx context.Context, token string) (*Session, error)
	DeleteSession(ctx context.Context, token string) error
	DeleteSessionsByUser(ctx context.Context, userID string) error
	DeleteExpiredSessions(ctx context.Context, now time.Time) error

	// Auth token ops
	CreateAuthToken(ctx context.Context, t *AuthToken) error
	GetAuthToken(ctx context.Context, tokenHash string) (*AuthToken, error)
	ConsumeAuthToken(ctx context.Context, tokenHash string) error             // sets used_at = now; ErrNotFound if missing, ErrConflict if already used
	DeleteAuthTokensByUser(ctx context.Context, userID, purpose string) error // housekeeping: drop a user's outstanding tokens of a purpose

	// TOTP recovery code ops
	CreateRecoveryCodes(ctx context.Context, userID string, codeHashes []string) error // bulk insert; created_at now
	ConsumeRecoveryCode(ctx context.Context, userID, codeHash string) error            // mark used_at if exists+unused+belongs to user; ErrNotFound if no match (already used or wrong)
	DeleteRecoveryCodes(ctx context.Context, userID string) error                      // wipe all for a user (on disable / regenerate)

	// Backup ops
	// BackupTo writes a consistent snapshot of the database to destPath using
	// SQLite's VACUUM INTO, which is safe to run on a live WAL database.
	BackupTo(ctx context.Context, destPath string) error
}
